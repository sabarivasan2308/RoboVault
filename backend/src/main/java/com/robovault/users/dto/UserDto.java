package com.robovault.users.dto;

import com.robovault.users.model.User;
import com.robovault.users.model.UserRole;

import java.time.LocalDateTime;

public class UserDto {
    private String id;
    private String email;
    private String fullName;
    private String department;
    private String studentOrEmployeeId;
    private UserRole role;
    private boolean active;
    private LocalDateTime createdAt;

    public UserDto() {
    }

    public static UserDto fromEntity(User user) {
        UserDto dto = new UserDto();
        dto.setId(user.getId());
        dto.setEmail(user.getEmail());
        dto.setFullName(user.getFullName());
        dto.setDepartment(user.getDepartment());
        dto.setStudentOrEmployeeId(user.getStudentOrEmployeeId());
        dto.setRole(user.getRole());
        dto.setActive(user.isActive());
        dto.setCreatedAt(user.getCreatedAt());
        return dto;
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public String getStudentOrEmployeeId() {
        return studentOrEmployeeId;
    }

    public void setStudentOrEmployeeId(String studentOrEmployeeId) {
        this.studentOrEmployeeId = studentOrEmployeeId;
    }

    public UserRole getRole() {
        return role;
    }

    public void setRole(UserRole role) {
        this.role = role;
    }

    public boolean isActive() {
        return active;
    }

    public void setActive(boolean active) {
        this.active = active;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(LocalDateTime createdAt) {
        this.createdAt = createdAt;
    }
}
